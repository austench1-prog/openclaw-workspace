# 37路径 期望值计算 v1 (理想化, 照副图)
# ============ 锁定参数 ============
# 底仓: 止损20点, 止盈100点 (1:5)
# 区域A/B: 各50点区间. 进场点 50%, 底 0.705
# 所有分支概率 = 50%
# 手数 = 比例, 1 = 原始进场手数

# ---- 几何: 副图读出的点位 (以原始交易区间为坐标) ----
# 原始区: 0(底,止损-20点处) 到 1(顶,TP). 区间=120点跨度? 
# 不: 1:5 = 止损20 + 止盈100, 进场到TP=100, 进场到SL=20.
# 副图: 进场参考点们用分数标. 关键我们用"点数"算盈亏, 概率都50%.

# 简化但忠于图: 我们关心的是每笔交易"赢多少点/亏多少点", 概率50%.
# 区域内每笔交易的点数 (Chairman 22:09 已定, 50点区间):
#   A1/B1: 50%入场1手, 1:1, 赢+25 / 亏-25
#   A2/B2: 25%加4手, 1:3, 赢+37.5 / 亏-12.5 (每手)
#   A3/B3: 回50%减3手, 必正, +12.5/手 (低买高平)
#   A4/B4: 回50%加3手, 1:1, +25/-25 (每手)
#   剩余仓冲"最高TP": 用底仓TP=100点位置作为最高TP参考
# 底仓: +100(赢) / -20(亏)

P = 0.5
# 单区域"内部已实现盈亏"(点数, 手数加权) —— 按成功案例公式
# 碰25%成功: 3手×(+12.5 减仓) + 剩1手×(+37.5 到TPA) ... 加仓手最终混入最高TP
# 我们按 Chairman 公式: 碰25%成功净2手到最高TP; 没碰25%成功净4手到最高TP
# "最高TP" 相对各区域进场的点数: 取该区域到原始TP的剩余空间, 理想化设 = 50点(一个区间高度) 作冲顶增益/手
TP_top = 50.0   # 剩余仓每手冲最高TP的增益(点) —— 理想化, 一个区间高度

def region(name):
    # 返回该区域8种内部结局: (标签, 已实现点数(单区域,手数加权), 是否成功)
    # 碰25% 路径:
    #   成功(反弹减3): 减3手×+12.5 = +37.5 已落袋, 剩2手冲顶
    #     到顶: +37.5 + 2×TP_top ; 保本: +37.5 + 0(保本)
    #   失败(5手全损破第一stop): 5手 × -? 
    #     5手在25%加的(4手)+50%的(1手). 破第一stop点数: 区间底附近.
    #     理想化: 全损 = 5手 × -(到stop点数). 50%入场1手亏25, 25%入场4手各亏12.5
    #     第一stop全损: 1×(-25) + 4×(-12.5) = -25-50 = -75
    #     破Original(连底仓): -75 + 底仓-20 = -95
    # 没碰25% 路径:
    #   成功(加3手共4手到顶): 4×TP_top (1手原始+3手加, 都冲顶)
    #     到顶: 4×TP_top ; 保本: 0
    #   失败(4手破第一stop): 4手 × -25 = -100 (都是1:1的25点)
    #     破Original: -100 + 底仓-20 = -120
    return {
      "碰25%-反弹-到顶":   (37.5 + 2*TP_top, True),
      "碰25%-反弹-保本":   (37.5,            True),
      "碰25%-失败-第一stop": (-75.0,          False),
      "碰25%-失败-Original":(-95.0,           False),
      "没碰25%-到顶":      (4*TP_top,         True),
      "没碰25%-保本":      (0.0,              True),
      "没碰25%-失败-第一stop":(-100.0,         False),
      "没碰25%-失败-Original":(-120.0,         False),
    }

A = region("A"); B = region("B")
BASE_WIN = 100.0   # 底仓赢
BASE_LOSS = -20.0  # 底仓亏

leaves = []
# 叶1: 原始直接失败
leaves.append(("叶1 原始直接失败", BASE_LOSS, P_orig_fail:=0.5))

# 原始成功 概率0.5, 之后进A. A内部8种, 每种(碰25/没碰)先0.5选路径, 再0.5成败...
# 但我们已把"8种结局"展开, 每种结局概率 = 0.5(碰/没碰) × 0.5(成/败子分支结构)
# 碰25%下有4结局: 0.5(碰) × [反弹成0.5 ×(到顶0.5/保本0.5)] + [反弹败0.5 ×(第一/Original 0.5)]
# 即每个最终结局概率 = 0.5(选路径)×0.5×0.5 = 0.125
def region_probs():
    return {
      "碰25%-反弹-到顶":   0.5*0.5*0.5,
      "碰25%-反弹-保本":   0.5*0.5*0.5,
      "碰25%-失败-第一stop": 0.5*0.5*0.5,
      "碰25%-失败-Original":0.5*0.5*0.5,
      "没碰25%-到顶":      0.5*0.5*0.5,
      "没碰25%-保本":      0.5*0.5*0.5,
      "没碰25%-失败-第一stop":0.5*0.5*0.5,
      "没碰25%-失败-Original":0.5*0.5*0.5,
    }
AP = region_probs()

P_orig_ok = 0.5
for a_label,(a_pnl,a_ok) in A.items():
    a_prob = P_orig_ok * AP[a_label]
    if not a_ok:
        # A失败终止, 总盈亏 = 底仓(此时原始还在挣扎; A失败破stop)
        # A的失败已含底仓情形(Original含-20). 第一stop型底仓还在=底仓未结(按0计未实现)
        total = a_pnl  # a_pnl已按是否连底仓编码
        leaves.append((f"原始✓→A:{a_label} [终止]", total, a_prob))
    else:
        for b_label,(b_pnl,b_ok) in B.items():
            b_prob = a_prob * AP[b_label]
            total = a_pnl + b_pnl   # A已实现 + B结局
            leaves.append((f"原始✓→A:{a_label}→B:{b_label}", total, b_prob))

# 校验概率和
psum = sum(p for _,_,p in leaves)
ev = sum(pnl*p for _,pnl,p in leaves)

print("="*70)
print("37路径 期望值 (理想化, 概率全50%, 底仓1:5=20/100点)")
print("="*70)
print(f"\n叶子数 = {len(leaves)}")
print(f"概率总和 = {psum:.4f} (应=1.0)")
print(f"\n【多策略模型 总期望 EV = {ev:+.2f} 点】")

# 对比: 单一1:5 (只做底仓, 不做内部A/B)
ev_single = 0.5*100 + 0.5*(-20)
print(f"【单一1:5  总期望 EV = {ev_single:+.2f} 点】  (50%×100 + 50%×(-20))")
print(f"\n>>> 差异: 多策略 {ev:+.2f} vs 单一 {ev_single:+.2f} 点")
print(f">>> {'多策略更优 ✅' if ev>ev_single else '单一1:5更优 ⚠️' if ev<ev_single else '相等'}")

# 极值
best = max(leaves, key=lambda x:x[1])
worst = min(leaves, key=lambda x:x[1])
print(f"\n最好: {best[1]:+.1f}点  {best[0][:40]}")
print(f"最坏: {worst[1]:+.1f}点  {worst[0][:40]}")
p_profit = sum(p for _,pnl,p in leaves if pnl>0)
print(f"盈利概率(PnL>0) = {p_profit:.1%}")

print("\n--- 全部37叶 (PnL点 | 概率) ---")
for lbl,pnl,p in leaves:
    print(f"  {pnl:+7.1f} | {p:.4f} | {lbl}")
