# v2 正确结构 (Chairman 01:04 定):
# 原始交易 = 前提, 概率1.0, 不参与概率计算 (我们假定方向成立才做)
# A, B = 两笔独立交易, 各自只用一次50%, 不相乘
# 模型总期望 = EV(A) + EV(B)   [独立 → 期望线性相加]
#
# "50%只用一次, 不相乘不加减" = 每笔交易内部 到顶/破止损 用一次50%

# ---- 单笔区域的期望: 一次50% ----
# 一个区域内, 进场后市场要么"成功(到顶)"要么"失败(破止损)", 各50%
# 但区域内部还有 碰25%/没碰25% 两条路径(这是走法, 不是概率削减)
# Chairman: 碰25%/没碰25% 只是同一个机会的两种展开, 不砍概率
#
# 简化忠实版: 一个区域 = 50%成功 / 50%失败 (一次50%)
#   成功的盈亏: 取决于走了哪条路(碰25%净2手到顶 / 没碰25%净4手到顶)
#   失败的盈亏: 取决于走了哪条路(碰25%全损 / 没碰25%全损)
# 走法本身(碰/没碰)也是50/50, 但它只决定"盈亏大小", 不再叠加生死概率

TP_top = 50.0   # 剩余仓每手冲顶增益(点), 理想化=一个区间高度

# 区域成功的两种盈亏(碰25% / 没碰25%), 各占成功内的50%走法
win_hit25   = 37.5 + 2*TP_top   # 碰25%成功: 减3手落袋37.5 + 剩2手到顶
win_no25    = 4*TP_top          # 没碰25%成功: 4手到顶
# 区域失败的两种盈亏
loss_hit25  = -75.0             # 碰25%失败: 5手全损(不连底仓, 底仓是前提另算)
loss_no25   = -100.0            # 没碰25%失败: 4手全损

# 单区域期望: 50%成功 × (走法平均) + 50%失败 × (走法平均)
# 走法各50%
win_avg  = 0.5*win_hit25 + 0.5*win_no25
loss_avg = 0.5*loss_hit25 + 0.5*loss_no25
EV_region = 0.5*win_avg + 0.5*loss_avg

print("="*64)
print("v2 正确结构: 原始=前提(100%), A/B各自独立一次50%, 盈亏相加")
print("="*64)
print(f"\n单区域内部:")
print(f"  成功(50%): 碰25%走法→{win_hit25:+.1f}点 | 没碰25%走法→{win_no25:+.1f}点 | 平均{win_avg:+.1f}")
print(f"  失败(50%): 碰25%走法→{loss_hit25:+.1f}点 | 没碰25%走法→{loss_no25:+.1f}点 | 平均{loss_avg:+.1f}")
print(f"  → 单区域期望 EV = 0.5×{win_avg:+.1f} + 0.5×{loss_avg:+.1f} = {EV_region:+.2f}点")

# A 和 B 同构, 各自独立, 盈亏相加
EV_A = EV_region
EV_B = EV_region
EV_multi = EV_A + EV_B
print(f"\n【多策略 = EV(A) + EV(B) = {EV_A:+.2f} + {EV_B:+.2f} = {EV_multi:+.2f}点】")

# 对比单一1:5 (底仓本身: 这里底仓是前提, 但作为对比, 单独1:5一笔)
EV_single = 0.5*100 + 0.5*(-20)
print(f"【单一1:5 一笔 = 0.5×100 + 0.5×(-20) = {EV_single:+.2f}点】")

print(f"\n>>> 多策略 {EV_multi:+.2f} vs 单一1:5 {EV_single:+.2f}")
print(f">>> {'多策略更优 ✅' if EV_multi>EV_single else '单一更优' if EV_multi<EV_single else '相等'}")

# 也给"两笔独立交易的完整分布"(各50%, 4种组合)
print(f"\n--- A、B 两笔独立交易的 4 种组合(各概率0.25) ---")
